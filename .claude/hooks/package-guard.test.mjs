for (const [want, commands] of Object.entries(cases)) {
  for (const c of commands) {
    test(`${want}: ${JSON.stringify(c)}`, () => {
      assert.equal(judge(c).decision, want);
    });
  }
}

test("a shell nested too deeply to check asks; a shallow one is judged", () => {
  const nest = (n) => { let c = "ls"; for (let k = 0; k < n; k++) c = `bash -c ${JSON.stringify(c)}`; return c; };
  assert.equal(judge(nest(6)).decision, "ask");
  assert.match(judge(nest(6)).reason, /nests shells too deeply/);
  assert.equal(judge(nest(3)).decision, "allow");
});

test("every deny and ask carries a reason that says what to do", () => {
  for (const c of [...cases.deny, ...cases.ask]) assert.match(judge(c).reason, /pnpm|owner approves/);
});

test("a long command is judged in linear time (the hook has a 10 s timeout)", () => {
  // Before the fix, "1&" repeated 500,000 times took about 50 s: each "&" tested the whole text before it.
  const slow = [("time bash -c ").repeat(1000) + "echo", "time " + "cargo ".repeat(200000), "sudo -E " + "cargo ".repeat(200000), "xargs " + "bash ".repeat(200000), "{".repeat(500000)];
  for (const c of ["1&".repeat(500000), "A=1 ".repeat(250000) + "npm i", "{(".repeat(500000), "uv run ".repeat(100000), ...slow]) {
    const t = Date.now();
    judge(c);
    assert.ok(Date.now() - t < 3000, `${c.slice(0, 8)}... took ${Date.now() - t} ms`);
  }
});

test("more prefixes than the guard reads ask, and never allow", () => {
  const r = judge("nice ".repeat(33) + "npm install");
  assert.equal(r.decision, "ask");
  assert.match(r.reason, /more prefixes than the guard reads/);
});
