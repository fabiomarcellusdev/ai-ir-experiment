// Selects gate C0.3's file set by the procedure in docs/contract.md ("The inputs, fixed before any run").
// It runs before any token count or view on a candidate: it reads a file's content only for the content rules.
// Usage, from the repository root: node experiments/c03/select-files.mjs
// Needs the GitHub CLI (`gh`), logged in. Writes experiments/c03/file-set.json (committed) and the drawn files to
// experiments/gate-files/<kind>/ (git-ignored: other people's content).
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const SEED = 20261110;
export const KINDS = [
  ['marketing', 'landing page language:HTML'],
  ['documentation', 'documentation site language:HTML'],
  ['email', 'email templates language:HTML'],
  ['app', 'admin dashboard language:HTML'],
  ['blog', 'blog template language:HTML'],
];
// OSI-approved licences, by GitHub's SPDX id. CC0-1.0 and "NOASSERTION" are not OSI-approved.
export const OSI = new Set(['MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', '0BSD', 'MPL-2.0', 'GPL-2.0',
  'GPL-3.0', 'LGPL-2.1', 'LGPL-3.0', 'AGPL-3.0', 'Unlicense', 'EPL-1.0', 'EPL-2.0', 'Zlib', 'BSL-1.0', 'Artistic-2.0',
  'MS-PL', 'UPL-1.0', 'MIT-0', 'ECL-2.0', 'OSL-3.0', 'EUPL-1.2', 'NCSA', 'PostgreSQL']);
const PATH_EXCLUDE = ['dist/', 'build/', '_site/', 'out/', 'node_modules/', 'vendor/', 'gh-pages'];
const POC_PAGES = ['wikipedia', 'developer.mozilla.org', 'github.com/nodejs/node', 'tailwindcss.com', 'news.ycombinator'];

// The draw: a Fisher-Yates shuffle with this generator (high bits of a 31-bit LCG), then the first 2 candidates
// that pass the content rules. A random order restricted to the passing files is a random order of those files, so
// this equals a draw of 2 from the filtered list, and it reads the content of fewer files.
export function shuffle(items, seed) {
  let s = seed;
  const rnd = (n) => { s = (s * 1103515245 + 12345) & 0x7fffffff; return (s >>> 16) % n; };
  const a = [...items];
  for (let i = a.length - 1; i > 0; i--) { const j = rnd(i + 1); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

export function pathRule(path, size) {
  if (!/\.html$/i.test(path)) return 'not .html';
  if (size < 10_000) return 'under 10 KB';
  if (size > 500_000) return 'over 500 KB';
  // A folder name, not a substring: "layout/" does not match "out/" (a bug in the first draw, 2026-11-11).
  const parts = path.toLowerCase().split('/').slice(0, -1);
  for (const x of PATH_EXCLUDE) if (parts.includes(x.replace(/\/$/, ''))) return `path has ${x}`;
  return null;
}

export function contentRule(text) {
  const long = text.split(/\r?\n/).findIndex((l) => l.length > 2000);
  if (long >= 0) return `line ${long + 1} is longer than 2,000 characters`;
  if (/<meta[^>]+name\s*=\s*["']?generator/i.test(text)) return 'meta name="generator"';
  if (/<!--[^>]*?\b(auto-?generated|generated by|do not edit)\b/i.test(text)) return 'a comment says it is generated';
  return null;
}

// The committed record: each repository with its commit, the count that each rule removed, the candidates that pass
// the path rules (path and size; the commit pins the rest), the files read in the draw order, and the picks.
export function compact(out) {
  const kinds = out.kinds.map((k) => {
    const removed = {};
    for (const c of k.allCandidates) if (c.rule) removed[c.rule] = (removed[c.rule] ?? 0) + 1;
    return {
      kind: k.kind, query: k.query, repos: k.repos, candidates: k.candidates, removedByPathRules: removed,
      passPathRules: k.allCandidates.filter((c) => !c.rule).map((c) => [c.repo, c.path, c.size]),
      readInDrawOrder: k.allCandidates.filter((c) => c.contentRule).map((c) => [c.repo, c.path, c.contentRule]),
      picks: k.picks.map(({ repo, commit, path, size, sha256, file }) => ({ repo, commit, path, size, sha256, file })),
    };
  });
  return { date: out.date, seed: out.seed, kinds };
}

const gh = (args) => {
  try {
    return JSON.parse(execFileSync('gh', ['api', ...args], { encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'pipe'] }));
  } catch (e) {
    throw new Error(`gh api ${args.join(' ')} failed: ${String(e.stderr ?? e.message).trim().slice(0, 200)}`);
  }
};
const raw = (repo, sha, path) => execFileSync('gh', ['api', '-H', 'Accept: application/vnd.github.raw',
  `repos/${repo}/contents/${path.split('/').map(encodeURIComponent).join('/')}?ref=${sha}`], { encoding: 'utf8', maxBuffer: 1 << 28 });

if (process.argv[1] && process.argv[1].endsWith('select-files.mjs')) {
  // --from-record: reuse the searches and the pinned commits of the committed record (no new search).
  const record = process.argv.includes('--from-record')
    ? JSON.parse(readFileSync('experiments/c03/file-set.json', 'utf8')) : null;
  const out = { date: record?.date ?? new Date().toISOString().slice(0, 10), seed: SEED, kinds: [] };
  for (const [kind, query] of KINDS) {
    const repos = record ? record.kinds.find((k) => k.kind === kind).repos.map((r) => ({ ...r })) : [];
    for (let page = 1; !record && repos.length < 20 && page <= 5; page++) {
      const res = gh(['-X', 'GET', 'search/repositories', '-f', `q=${query}`, '-f', 'sort=stars', '-f', 'order=desc',
        '-f', 'per_page=50', '-f', `page=${page}`]);
      for (const r of res.items) {
        if (repos.length >= 20) break;
        const lic = r.license?.spdx_id ?? null;
        if (OSI.has(lic)) repos.push({ repo: r.full_name, licence: lic, stars: r.stargazers_count, branch: r.default_branch });
      }
      if (!res.items.length) break;
    }
    const candidates = [];
    for (const r of repos) {
      r.commit ??= gh([`repos/${r.repo}/commits/${encodeURIComponent(r.branch)}`]).sha;
      const tree = gh([`repos/${r.repo}/git/trees/${r.commit}?recursive=1`]);
      r.treeTruncated = !!tree.truncated;
      for (const t of tree.tree) {
        if (t.type !== 'blob' || !/\.html$/i.test(t.path)) continue;
        const rule = pathRule(t.path, t.size) ?? (POC_PAGES.some((p) => r.repo.includes(p)) ? 'a POC page' : null);
        candidates.push({ repo: r.repo, commit: r.commit, path: t.path, size: t.size, rule });
      }
    }
    const order = shuffle(candidates.filter((c) => !c.rule), SEED);
    rmSync(join('experiments', 'gate-files', kind), { recursive: true, force: true });
    const picks = [];
    for (const c of order) {
      if (picks.length === 2) break;
      const text = raw(c.repo, c.commit, c.path);
      c.contentRule = contentRule(text) ?? 'pass';
      if (c.contentRule !== 'pass') continue;
      c.sha256 = createHash('sha256').update(text, 'utf8').digest('hex');
      const dir = join('experiments', 'gate-files', kind);
      mkdirSync(dir, { recursive: true });
      const file = `${picks.length + 1}-${c.path.split('/').pop()}`;
      writeFileSync(join(dir, file), text);
      picks.push({ ...c, file: `experiments/gate-files/${kind}/${file}` });
    }
    out.kinds.push({ kind, query, repos, candidates: candidates.length, drawOrderChecked: order.filter((c) => c.contentRule).length, picks, allCandidates: candidates });
    console.log(`${kind}: ${repos.length} repositories, ${candidates.length} .html files, ${order.length} pass the path rules, picks: ${picks.map((p) => `${p.repo}/${p.path}`).join(', ')}`);
  }
  writeFileSync('experiments/c03/file-set.json', JSON.stringify(compact(out)) + '\n');
}
