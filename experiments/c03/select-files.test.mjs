import { test } from 'node:test';
import assert from 'node:assert/strict';
import { pathRule, contentRule, shuffle } from './select-files.mjs';

test('regression: a path rule matches a folder name, not a substring', () => {
  // Fails with the bug put back: "templates/layout/page.html" was removed as "path has out/".
  assert.equal(pathRule('templates/layout/page.html', 20_000), null);
  assert.equal(pathRule('docs/about/index.html', 20_000), null);
  assert.equal(pathRule('rebuild/x.html', 20_000), null);
  assert.equal(pathRule('out/index.html', 20_000), 'path has out/');
  assert.equal(pathRule('site/dist/a.html', 20_000), 'path has dist/');
  assert.equal(pathRule('gh-pages/a.html', 20_000), 'path has gh-pages');
});

test('size and extension rules', () => {
  assert.equal(pathRule('a.html', 9_999), 'under 10 KB');
  assert.equal(pathRule('a.html', 10_000), null);
  assert.equal(pathRule('a.html', 500_001), 'over 500 KB');
  assert.equal(pathRule('a.htm', 20_000), 'not .html');
});

test('content rules find minified and generated files', () => {
  assert.equal(contentRule('<p>ok</p>\n<p>fine</p>'), null);
  assert.match(contentRule('<p>' + 'x'.repeat(2001) + '</p>'), /longer than 2,000/);
  assert.match(contentRule('<meta name="generator" content="Hugo">'), /generator/);
  assert.match(contentRule('<!-- Generated by Sphinx -->'), /generated/);
});

test('the shuffle is a fixed permutation for a seed', () => {
  const a = shuffle([1, 2, 3, 4, 5, 6, 7, 8], 20261110);
  assert.deepEqual([...a].sort(), [1, 2, 3, 4, 5, 6, 7, 8]);
  assert.deepEqual(shuffle([1, 2, 3, 4, 5, 6, 7, 8], 20261110), a);
  assert.notDeepEqual(shuffle([1, 2, 3, 4, 5, 6, 7, 8], 1), a);
});
